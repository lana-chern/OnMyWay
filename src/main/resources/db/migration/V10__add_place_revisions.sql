CREATE TABLE place_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    latitude NUMERIC(9, 6) NOT NULL,
    longitude NUMERIC(9, 6) NOT NULL,
    status VARCHAR(32) NOT NULL,
    rejection_reason TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_place_revisions_place FOREIGN KEY (place_id) REFERENCES places (id),
    CONSTRAINT uk_place_revisions_place_id UNIQUE (place_id, id)
);

CREATE UNIQUE INDEX uk_place_revisions_one_working_per_place
    ON place_revisions (place_id)
    WHERE status IN ('DRAFT', 'PENDING_MODERATION', 'REJECTED');

CREATE UNIQUE INDEX uk_place_revisions_one_published_per_place
    ON place_revisions (place_id)
    WHERE status = 'PUBLISHED';

CREATE INDEX idx_place_revisions_moderation_queue
    ON place_revisions (created_at, id)
    WHERE status = 'PENDING_MODERATION';

INSERT INTO place_revisions (
    place_id, version, name, description, latitude, longitude, status,
    rejection_reason, created_at, updated_at
)
SELECT
    p.id,
    p.version,
    p.name,
    p.description,
    p.latitude,
    p.longitude,
    CASE p.status
        WHEN 'DRAFT' THEN 'DRAFT'
        WHEN 'PENDING_MODERATION' THEN 'PENDING_MODERATION'
        WHEN 'PUBLISHED' THEN 'PUBLISHED'
        WHEN 'REJECTED' THEN 'REJECTED'
        WHEN 'ARCHIVED' THEN 'ARCHIVED'
    END,
    p.rejection_reason,
    p.created_at,
    p.updated_at
FROM places p;

INSERT INTO place_revision_photos (revision_id, url, position, description)
SELECT r.id, photo.url, photo.position, photo.description
FROM place_photos photo
JOIN place_revisions r ON r.place_id = photo.place_id;

INSERT INTO place_revision_contacts (revision_id, type, contact_value)
SELECT r.id, contact.type, contact.contact_value
FROM place_contacts contact
JOIN place_revisions r ON r.place_id = contact.place_id;

INSERT INTO place_revision_opening_hours (
    revision_id, day_of_week, opening_time, closing_time, closed
)
SELECT r.id, hours.day_of_week, hours.opening_time, hours.closing_time, hours.closed
FROM place_opening_hours hours
JOIN place_revisions r ON r.place_id = hours.place_id;

ALTER TABLE places ADD COLUMN published_revision_id BIGINT;

UPDATE places p
SET published_revision_id = r.id
FROM place_revisions r
WHERE r.place_id = p.id
  AND r.status = 'PUBLISHED';

ALTER TABLE places
    ADD CONSTRAINT fk_places_published_revision
    FOREIGN KEY (id, published_revision_id)
    REFERENCES place_revisions (place_id, id);

CREATE INDEX idx_places_published_revision_id
    ON places (published_revision_id)
    WHERE published_revision_id IS NOT NULL;
